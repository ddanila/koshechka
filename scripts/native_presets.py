"""Generate native model constants from the canonical Python presets."""
from pathlib import Path
import sys
import re
import math
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'reconstruction'))
from kitty.core import initial_legs
from kitty.geometry import cat
from kitty.presets import PRESETS


def array(values):
    return '{'+','.join(array(v) if isinstance(v,(list,tuple)) else repr(v) for v in values)+'}'


def generate():
    chunks=['/* Generated by scripts/native_presets.py; do not edit. */']
    for name,model in PRESETS.items():
        root,_=cat(dict(t=0.,legs=[l.state for l in initial_legs()]),model)
        rows=[]
        def visit(node,parent=-1,leg=-1,segment=-1):
            index=len(rows)
            if node.name in ('right_rear','right_front','left_rear','left_front'):
                leg=('right_rear','right_front','left_rear','left_front').index(node.name)
            rows.append([node.origin,node.rotation,node.scale,node.dimensions or [0.]*4,
                         parent,int(node.dimensions is not None),leg,segment,int(node.name=='head')])
            for j,child in enumerate(node.children):
                visit(child,index,leg,j if leg>=0 else -1)
        visit(root)
        assert len(rows)==36
        chunks.append('static const Node '+name+'_nodes[NN] = '+array(rows)+';')
        chunks.append('static const double '+name+'_lengths[3] = '+array(model['leg_lengths'])+';')
        chunks.append('static const double '+name+'_foot = '+repr(model['foot_length'])+';')
        chunks.append('static const double '+name+'_d = '+repr(model['d'])+';')
        chunks.append('static const double '+name+'_angle = '+repr(model['view_yaw_degrees'])+';')
    return '\n'.join(chunks)+'\n'

if __name__=='__main__':
    target=Path(__file__).resolve().parents[1]/'native/presets.h'
    if '--check' in sys.argv:
        # libm differs in the last bits across macOS/Linux. Compare structure
        # exactly and floating constants at the same tight scale as pose tests.
        pattern=r'([-+]?(?:[0-9]+\.[0-9]*|[0-9]*\.[0-9]+)(?:e[-+]?[0-9]+)?)'
        saved=re.split(pattern,target.read_text())
        fresh=re.split(pattern,generate())
        assert len(saved)==len(fresh),'Regenerate native presets (structure)'
        for index,(a,b) in enumerate(zip(saved,fresh)):
            assert (math.isclose(float(a),float(b),rel_tol=1e-12,abs_tol=1e-12)
                    if index%2 else a==b),'Regenerate native presets (model changed)'
    else:target.write_text(generate())
